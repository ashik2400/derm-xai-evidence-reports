"""Step 1.6: write reports/data_report.md plus figures from data/processed/cases.csv.

Run from the repo root (after build_cases):
    conda run -n derm python -m src.data.data_report
"""
import matplotlib
matplotlib.use("Agg")  # draw to files, no window
import matplotlib.pyplot as plt
import pandas as pd
from PIL import Image
from sklearn.metrics import balanced_accuracy_score

from src import config

SPLITS = ["train", "valid", "test"]
CLASSES = ["nevus", "melanoma", "miscellaneous", "seborrheic keratosis", "basal cell carcinoma"]
CONCEPTS = ["pigment_network", "streaks", "pigmentation", "regression_structures",
            "dots_and_globules", "blue_whitish_veil", "vascular_structures"]
METADATA = ["elevation", "location", "sex"]                      # allowed model inputs
LEAKY = ["management", "level_of_diagnostic_difficulty", "seven_point_score"]  # audit only


def md_table(df):
    """DataFrame -> markdown table (keeps us free of extra packages)."""
    df = df.reset_index()
    lines = ["| " + " | ".join(map(str, df.columns)) + " |",
             "|" + "---|" * len(df.columns)]
    lines += ["| " + " | ".join(map(str, row)) + " |" for row in df.values]
    return "\n".join(lines)


def class_split_figure(cases):
    counts = pd.crosstab(cases["diagnosis_5"], cases["split"]).reindex(CLASSES)[SPLITS]
    ax = counts.plot.bar(figsize=(8, 4), rot=20)
    ax.set_ylabel("cases"); ax.set_title("5-class counts per official split")
    plt.tight_layout(); plt.savefig(config.FIGURES_DIR / "class_per_split.png", dpi=120); plt.close()


def sample_grid(cases):
    """One train case per class: dermoscopic (top) and clinical (bottom)."""
    fig, axes = plt.subplots(2, len(CLASSES), figsize=(3 * len(CLASSES), 6))
    for j, cls in enumerate(CLASSES):
        row = cases[(cases.diagnosis_5 == cls) & cases.has_clinic & (cases.split == "train")].iloc[0]
        for i, col in enumerate(["derm_path", "clinic_path"]):
            axes[i, j].imshow(Image.open(config.IMAGES_DIR / row[col]))
            axes[i, j].axis("off")
        axes[0, j].set_title(f"{cls}\n(case {row.case_num})", fontsize=9)
    axes[0, 0].text(-0.1, 0.5, "dermoscopic", transform=axes[0, 0].transAxes, rotation=90, va="center", ha="right")
    axes[1, 0].text(-0.1, 0.5, "clinical", transform=axes[1, 0].transAxes, rotation=90, va="center", ha="right")
    plt.tight_layout(); plt.savefig(config.FIGURES_DIR / "sample_images.png", dpi=100); plt.close()


def one_rule_accuracy(cases, column):
    """Leakage preview: predict each test case's class as the most common train class
    for that column value. High accuracy = the column alone gives the answer away."""
    train, test = cases[cases.split == "train"], cases[cases.split == "test"]
    rule = train.groupby(column)["diagnosis_5"].agg(lambda s: s.mode()[0])
    fallback = train["diagnosis_5"].mode()[0]
    pred = test[column].map(rule).fillna(fallback)
    # balanced accuracy = mean recall over the 5 classes (always-nevus scores 20%)
    return balanced_accuracy_score(test["diagnosis_5"], pred)


def main():
    cases = pd.read_csv(config.CASES_CSV)
    config.FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    class_split_figure(cases)
    sample_grid(cases)

    out = ["# Derm7pt data report", "",
           f"Generated by `src/data/data_report.py` from `{config.CASES_CSV.relative_to(config.ROOT).as_posix()}`.", "",
           f"- Cases: **{len(cases)}** (official split: "
           + ", ".join(f"{s} {(cases.split == s).sum()}" for s in SPLITS) + ")",
           f"- Cases with no real clinical image: **{(~cases.has_clinic).sum()}** "
           "(the `clinic` file is a copy of the dermoscopic one). Rule: keep them, zero clinical input + missing flag.",
           "", "## 1. Classes per split", "",
           md_table(pd.crosstab(cases.diagnosis_5, cases.split, margins=True).reindex(CLASSES + ["All"])[SPLITS + ["All"]]),
           "", "![classes](figures/class_per_split.png)", "",
           "Train baseline: always predicting *nevus* scores "
           f"{(cases[cases.split == 'test'].diagnosis_5 == 'nevus').mean():.1%} accuracy on test. "
           "This is why we report balanced accuracy / per-class metrics, not plain accuracy.", "",
           "## 2. Sample images (train)", "", "![samples](figures/sample_images.png)", "",
           "## 3. Metadata (allowed model inputs)", ""]
    for col in METADATA:
        out += [f"### {col}", "", md_table(pd.crosstab(cases[col], cases.diagnosis_5)[CLASSES]), ""]

    out += ["## 4. The 7 concepts (training targets only; predicted from images at test time)", ""]
    for col in CONCEPTS:
        out += [f"### {col}", "", md_table(pd.crosstab(cases[col], cases.diagnosis_5)[CLASSES]), ""]

    out += ["## 5. Leakage preview (NOT model inputs)", "",
            "One-rule check: for each column, map every value to its most common class in train, "
            "then score that rule on test with balanced accuracy (always-nevus = 20%). A column far "
            "above 20% carries class information; for the leaky columns that information comes from "
            "the doctor's decision, not the lesion. The full audit is research question 3.", "",
            "| column | one-rule test balanced accuracy |", "|---|---|"]
    for col in LEAKY + METADATA:
        out.append(f"| {col} | {one_rule_accuracy(cases, col):.1%} |")
    out += ["", "**Caution:** the one-rule check underestimates leakage. A column can rule classes *out* "
            "without making a minority class the most common value. Example below: every melanoma and BCC "
            "was excised, and no 'clinical follow up' case is melanoma. Combined with images, this is a strong "
            "shortcut. RQ3 measures it properly by adding these columns to the fusion model.",
            "", "### management vs class", "",
            md_table(pd.crosstab(cases.management, cases.diagnosis_5)[CLASSES]), "",
            "### seven_point_score: mean per class", "",
            md_table(cases.groupby("diagnosis_5")["seven_point_score"].agg(["mean", "std"]).round(2).reindex(CLASSES)), ""]

    path = config.REPORTS_DIR / "data_report.md"
    path.write_text("\n".join(out), encoding="utf-8")
    print("Wrote", path.relative_to(config.ROOT))
    for col in LEAKY + METADATA:
        print(f"  one-rule balanced acc  {col:32s} {one_rule_accuracy(cases, col):.1%}")


if __name__ == "__main__":
    main()
